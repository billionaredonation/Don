export function utilitySupplyReason(bill, service) {
  if (bill?.[{ electricity: 'powerActive', water: 'waterActive', gas: 'gasActive' }[service]]) return '';
  const reason = bill?.suspendedReason || bill?.suspended_reason;
  const messages = {
    plant_stopped: service === 'gas'
      ? 'Поставщик отключил подачу газа. Владельцу УкрГаза нужно запустить поставку.'
      : 'Водоочистное предприятие остановлено. Владельцу нужно запустить его.',
    storage_empty: {
      electricity: 'В накопителе подстанции нет энергии. Поставщику нужно проверить поступление электричества.',
      water: 'У поставщика закончилась очищенная вода. Нужно проверить работу очистки и запас воды.',
      gas: 'У поставщика закончился готовый газ. Нужно проверить уголь, матрицу и её обслуживание.',
    }[service],
    transformer_inactive: 'Трансформатор отключён. Владельцу подстанции нужно проверить его состояние и обслуживание.',
    transformer_maintenance: 'Трансформатор требует ручной оплаты обслуживания владельцем подстанции.',
    maintenance_required: 'Оборудование требует обслуживания владельцем предприятия.',
    supply_unavailable: 'Поставка от источника недоступна. Владельцу нужно проверить источник и договор поставки.',
    consumer_balance: 'Сервер приостановил поставку из-за недостатка средств потребителя.',
    owner_changed: 'Владелец объекта изменился. Требуется новый договор.',
  };
  if (messages[reason]) return messages[reason];
  if (bill?.status === 'cancelled') return 'Договор прекращён. Нужно заключить новый.';
  if (bill?.status === 'rejected') return 'Предложение договора отклонено.';
  if (bill?.status === 'offered') return 'Договор ожидает принятия владельцем объекта.';
  return 'Сервер не передал причину остановки. Проверьте состояние предприятия-поставщика.';
}

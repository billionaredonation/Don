create or replace function public.hospital_list_employees(p_hospital_id text, p_actor_tg_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_employees jsonb;
begin
  select * into v_access from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);

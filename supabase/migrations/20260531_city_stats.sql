create or replace function public.hospital_rank_level(p_rank text)
returns integer
language sql
immutable
as $$
  select case lower(coalesce(p_rank, ''))
    when 'junior' then 1
    when 'middle' then 2
    when 'senior' then 3
    when 'admin' then 4
    else 0
  end;
$$;

create or replace function public.hospital_player_is_admin(p_tg_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select p.is_admin is true
    from public.players p
    where p.tg_id::text = trim(coalesce(p_tg_id, ''))
    limit 1
  ), false);
$$;

create or replace function public.hospital_resolve_player_tg_id(p_target text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select p.tg_id::text
  from public.players p
  where p.tg_id::text = trim(coalesce(p_target, ''))
     or lower(p.nickname::text) = lower(trim(coalesce(p_target, '')))
  order by case when p.tg_id::text = trim(coalesce(p_target, '')) then 0 else 1 end
  limit 1;
$$;

create or replace function public.hospital_ensure(p_hospital_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hospital_id text := trim(coalesce(p_hospital_id, ''));
begin
  if v_hospital_id = '' or length(v_hospital_id) > 160 then
    raise exception 'HOSPITAL_ID_INVALID';
  end if;

  insert into public.hospital_settings(hospital_id)
  values (v_hospital_id)
  on conflict (hospital_id) do nothing;

  insert into public.hospital_item_catalog(
    hospital_id, item_type, label, icon, heal_per_tick, tick_seconds,
    duration_seconds, min_health, max_health, min_food,
    min_take_rank, min_treat_rank, min_sell_rank, sale_price
  ) values
    (v_hospital_id, 'food', 'Продукты', '🍱', 0, 0, 0, 0, 100, 0, 2, 3, 3, 0),
    (v_hospital_id, 'medicine_light', 'Простые таблетки', '💊', 0.5, 10, 60, 50, 100, 40, 1, 1, 2, 0),
    (v_hospital_id, 'medicine_strong', 'Сильные таблетки', '💉', 2, 5, 60, 15, 50, 40, 3, 3, 3, 0),
    (v_hospital_id, 'medicine_resuscitation', 'Реанимационные таблетки', '⚕', 7.5, 2, 60, 0, 15, 40, 3, 3, 3, 0)
  on conflict (hospital_id, item_type) do nothing;

  insert into public.hospital_warehouse_stock(hospital_id, item_type, quantity)
  select v_hospital_id, c.item_type, 0
  from public.hospital_item_catalog c
  where c.hospital_id = v_hospital_id
  on conflict (hospital_id, item_type) do nothing;

  insert into public.hospital_finances(hospital_id, balance)
  values (v_hospital_id, 0)
  on conflict (hospital_id) do nothing;
end;
$$;

create or replace function public.hospital_get_actor_access(p_hospital_id text, p_actor_tg_id text)
returns table(is_admin boolean, employee_access_enabled boolean, rank text, rank_level integer, allowed boolean)
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.hospital_ensure(p_hospital_id);

  return query
  select
    public.hospital_player_is_admin(p_actor_tg_id),
    hs.employee_access_enabled,
    case
      when public.hospital_player_is_admin(p_actor_tg_id) then 'admin'
      else he.rank
    end,
    case
      when public.hospital_player_is_admin(p_actor_tg_id) then 4
      else public.hospital_rank_level(he.rank)
    end,
    public.hospital_player_is_admin(p_actor_tg_id)
      or (hs.employee_access_enabled and he.active is true and he.rank is not null)
  from public.hospital_settings hs
  left join public.hospital_employees he
    on he.hospital_id = hs.hospital_id
   and he.employee_tg_id = trim(coalesce(p_actor_tg_id, ''))
   and he.active is true
  where hs.hospital_id = trim(coalesce(p_hospital_id, ''));
end;
$$;

create or replace function public.hospital_get_context(p_hospital_id text, p_actor_tg_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_items jsonb;
begin
  select * into v_access
  from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);

  select coalesce(jsonb_agg(jsonb_build_object(
    'itemType', c.item_type,
    'label', c.label,
    'icon', c.icon,
    'healPerTick', c.heal_per_tick,
    'tickSeconds', c.tick_seconds,
    'durationSeconds', c.duration_seconds,
    'minHealth', c.min_health,
    'maxHealth', c.max_health,
    'minFood', c.min_food,
    'salePrice', c.sale_price,
    'warehouseQuantity', coalesce(s.quantity, 0),
    'personalQuantity', coalesce(i.quantity, 0)
  ) order by case c.item_type
    when 'food' then 1
    when 'medicine_light' then 2
    when 'medicine_strong' then 3
    else 4
  end), '[]'::jsonb)
  into v_items
  from public.hospital_item_catalog c
  left join public.hospital_warehouse_stock s
    on s.hospital_id = c.hospital_id and s.item_type = c.item_type
  left join public.hospital_employee_inventory i
    on i.hospital_id = c.hospital_id
   and i.item_type = c.item_type
   and i.employee_tg_id = trim(coalesce(p_actor_tg_id, ''))
  where c.hospital_id = trim(coalesce(p_hospital_id, ''))
    and c.enabled is true;

  return jsonb_build_object(
    'allowed', coalesce(v_access.allowed, false),
    'reason', case
      when coalesce(v_access.allowed, false) then null
      when coalesce(v_access.employee_access_enabled, false) is false then 'ADMIN_ONLY'
      else 'NO_HOSPITAL_RANK'
    end,
    'isAdmin', coalesce(v_access.is_admin, false),
    'employeeAccessEnabled', coalesce(v_access.employee_access_enabled, false),
    'rank', coalesce(v_access.rank, ''),
    'permissions', jsonb_build_object(
      'canRefill', coalesce(v_access.is_admin, false) or coalesce(v_access.rank_level, 0) >= 3,
      'canOrderFood', coalesce(v_access.is_admin, false) or coalesce(v_access.rank_level, 0) >= 2,
      'canManageEmployees', coalesce(v_access.is_admin, false) or coalesce(v_access.rank_level, 0) >= 3,
      'canViewStats', coalesce(v_access.is_admin, false) or coalesce(v_access.rank_level, 0) >= 3
    ),
    'items', v_items
  );
end;
$$;

create or replace function public.hospital_refill_stock(
  p_hospital_id text, p_actor_tg_id text, p_item_type text, p_quantity bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_after bigint;
begin
  if coalesce(p_quantity, 0) <= 0 or p_quantity > 100000 then raise exception 'QUANTITY_INVALID'; end if;
  select * into v_access from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);
  if not coalesce(v_access.allowed, false) then raise exception 'HOSPITAL_ACCESS_DENIED'; end if;
  if not v_access.is_admin and v_access.rank_level < 3 then raise exception 'REFILL_RANK_REQUIRED'; end if;

  update public.hospital_warehouse_stock
  set quantity = quantity + p_quantity, updated_by_tg_id = p_actor_tg_id, updated_at = now()
  where hospital_id = trim(p_hospital_id) and item_type = p_item_type
  returning quantity into v_after;
  if v_after is null then raise exception 'ITEM_NOT_FOUND'; end if;

  insert into public.hospital_stock_movements(hospital_id, actor_tg_id, item_type, movement_type, quantity, balance_after)
  values (trim(p_hospital_id), trim(p_actor_tg_id), p_item_type, 'refill', p_quantity, v_after);
  return jsonb_build_object('quantity', v_after);
end;
$$;

create or replace function public.hospital_take_stock(
  p_hospital_id text, p_actor_tg_id text, p_item_type text, p_quantity bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_min_rank integer;
  v_after bigint;
begin
  if coalesce(p_quantity, 0) <= 0 or p_quantity > 100000 then raise exception 'QUANTITY_INVALID'; end if;
  select * into v_access from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);
  if not coalesce(v_access.allowed, false) then raise exception 'HOSPITAL_ACCESS_DENIED'; end if;

  select min_take_rank into v_min_rank
  from public.hospital_item_catalog
  where hospital_id = trim(p_hospital_id) and item_type = p_item_type and enabled is true;
  if v_min_rank is null then raise exception 'ITEM_NOT_FOUND'; end if;
  if not v_access.is_admin and v_access.rank_level < v_min_rank then raise exception 'ITEM_RANK_REQUIRED'; end if;

  update public.hospital_warehouse_stock
  set quantity = quantity - p_quantity, updated_by_tg_id = p_actor_tg_id, updated_at = now()
  where hospital_id = trim(p_hospital_id) and item_type = p_item_type and quantity >= p_quantity
  returning quantity into v_after;
  if v_after is null then raise exception 'WAREHOUSE_STOCK_NOT_ENOUGH'; end if;

  insert into public.hospital_employee_inventory(hospital_id, employee_tg_id, item_type, quantity)
  values (trim(p_hospital_id), trim(p_actor_tg_id), p_item_type, p_quantity)
  on conflict (hospital_id, employee_tg_id, item_type) do update
    set quantity = hospital_employee_inventory.quantity + excluded.quantity, updated_at = now();

  insert into public.hospital_stock_movements(hospital_id, actor_tg_id, target_tg_id, item_type, movement_type, quantity, balance_after)
  values (trim(p_hospital_id), trim(p_actor_tg_id), trim(p_actor_tg_id), p_item_type, 'take', p_quantity, v_after);
  return jsonb_build_object('warehouseQuantity', v_after);
end;
$$;


create or replace function public.hospital_treat_player(
  p_hospital_id text, p_actor_tg_id text, p_target text, p_medicine_type text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_patient_tg_id text;
  v_patient public.players%rowtype;
  v_catalog public.hospital_item_catalog%rowtype;
  v_patient_nickname text;
begin
  select * into v_access from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);
  if not coalesce(v_access.allowed, false) then raise exception 'HOSPITAL_ACCESS_DENIED'; end if;

  select * into v_catalog
  from public.hospital_item_catalog
  where hospital_id = trim(p_hospital_id)
    and item_type = p_medicine_type
    and item_type like 'medicine_%'
    and enabled is true;
  if not found then raise exception 'MEDICINE_NOT_FOUND'; end if;
  if not v_access.is_admin and v_access.rank_level < v_catalog.min_treat_rank then raise exception 'TREATMENT_RANK_REQUIRED'; end if;

  v_patient_tg_id := public.hospital_resolve_player_tg_id(p_target);
  if v_patient_tg_id is null then raise exception 'PLAYER_NOT_FOUND'; end if;
  select * into v_patient from public.players where tg_id::text = v_patient_tg_id for update;
  v_patient_nickname := coalesce(v_patient.nickname, 'Игрок');
  if v_patient.food < v_catalog.min_food then raise exception 'PATIENT_FOOD_TOO_LOW'; end if;
  if v_patient.health >= 100 then raise exception 'PATIENT_HEALTH_FULL'; end if;
  if v_patient.health < v_catalog.min_health or v_patient.health >= v_catalog.max_health then
    raise exception 'MEDICINE_HEALTH_RANGE_MISMATCH';
  end if;
  if exists (
    select 1 from public.hospital_treatment_effects
    where patient_tg_id = v_patient_tg_id and status = 'active'
  ) then raise exception 'PATIENT_ALREADY_TREATED'; end if;

  update public.hospital_employee_inventory
  set quantity = quantity - 1, updated_at = now()
  where hospital_id = trim(p_hospital_id)
    and employee_tg_id = trim(p_actor_tg_id)
    and item_type = p_medicine_type
    and quantity >= 1;
  if not found then raise exception 'PERSONAL_MEDICINE_NOT_ENOUGH'; end if;

  insert into public.hospital_treatment_effects(
    hospital_id, patient_tg_id, clinician_tg_id, medicine_type,
    heal_per_tick, tick_seconds, expires_at
  ) values (
    trim(p_hospital_id), v_patient_tg_id, trim(p_actor_tg_id), p_medicine_type,
    v_catalog.heal_per_tick, v_catalog.tick_seconds, now() + make_interval(secs => v_catalog.duration_seconds)
  );

  insert into public.hospital_employee_stats(hospital_id, employee_tg_id, players_treated, medicines_given)
  values (trim(p_hospital_id), trim(p_actor_tg_id), 1, 1)
  on conflict (hospital_id, employee_tg_id) do update
    set players_treated = hospital_employee_stats.players_treated + 1,
        medicines_given = hospital_employee_stats.medicines_given + 1,
        updated_at = now();
  insert into public.hospital_stock_movements(hospital_id, actor_tg_id, target_tg_id, item_type, movement_type, quantity)
  values (trim(p_hospital_id), trim(p_actor_tg_id), v_patient_tg_id, p_medicine_type, 'treat', 1);

  return jsonb_build_object('patientTgId', v_patient_tg_id, 'patientNickname', v_patient_nickname, 'durationSeconds', v_catalog.duration_seconds);
end;
$$;

create or replace function public.hospital_sell_medicine(
  p_hospital_id text, p_actor_tg_id text, p_target text, p_medicine_type text, p_quantity bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_buyer_tg_id text;
  v_catalog public.hospital_item_catalog%rowtype;
  v_total bigint;
begin
  if coalesce(p_quantity, 0) <= 0 or p_quantity > 1000 then raise exception 'QUANTITY_INVALID'; end if;
  select * into v_access from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);
  if not coalesce(v_access.allowed, false) then raise exception 'HOSPITAL_ACCESS_DENIED'; end if;
  select * into v_catalog
  from public.hospital_item_catalog
  where hospital_id = trim(p_hospital_id) and item_type = p_medicine_type and item_type like 'medicine_%' and enabled is true;
  if not found then raise exception 'MEDICINE_NOT_FOUND'; end if;
  if not v_access.is_admin and v_access.rank_level < v_catalog.min_sell_rank then raise exception 'SALE_RANK_REQUIRED'; end if;
  if v_catalog.sale_price <= 0 then raise exception 'SALE_PRICE_NOT_CONFIGURED'; end if;

  v_buyer_tg_id := public.hospital_resolve_player_tg_id(p_target);
  if v_buyer_tg_id is null then raise exception 'PLAYER_NOT_FOUND'; end if;
  v_total := v_catalog.sale_price * p_quantity;

  update public.hospital_employee_inventory
  set quantity = quantity - p_quantity, updated_at = now()
  where hospital_id = trim(p_hospital_id) and employee_tg_id = trim(p_actor_tg_id)
    and item_type = p_medicine_type and quantity >= p_quantity;
  if not found then raise exception 'PERSONAL_MEDICINE_NOT_ENOUGH'; end if;

  update public.players
  set balance = balance - v_total
  where tg_id::text = v_buyer_tg_id and balance >= v_total;
  if not found then raise exception 'BUYER_BALANCE_NOT_ENOUGH'; end if;

  insert into public.player_medical_inventory(player_tg_id, item_type, quantity)
  values (v_buyer_tg_id, p_medicine_type, p_quantity)
  on conflict (player_tg_id, item_type) do update
    set quantity = player_medical_inventory.quantity + excluded.quantity, updated_at = now();
  update public.hospital_finances set balance = balance + v_total, updated_at = now()
  where hospital_id = trim(p_hospital_id);
  insert into public.hospital_employee_stats(hospital_id, employee_tg_id, medicines_sold, revenue)
  values (trim(p_hospital_id), trim(p_actor_tg_id), p_quantity, v_total)
  on conflict (hospital_id, employee_tg_id) do update
    set medicines_sold = hospital_employee_stats.medicines_sold + excluded.medicines_sold,
        revenue = hospital_employee_stats.revenue + excluded.revenue,
        updated_at = now();
  insert into public.hospital_stock_movements(hospital_id, actor_tg_id, target_tg_id, item_type, movement_type, quantity, metadata)
  values (trim(p_hospital_id), trim(p_actor_tg_id), v_buyer_tg_id, p_medicine_type, 'sell', p_quantity, jsonb_build_object('totalPrice', v_total));
  return jsonb_build_object('buyerTgId', v_buyer_tg_id, 'quantity', p_quantity, 'totalPrice', v_total);
end;
$$;

create or replace function public.hospital_process_my_treatment(p_patient_tg_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_effect public.hospital_treatment_effects%rowtype;
  v_health numeric(5,1);
  v_until timestamptz;
  v_ticks integer;
  v_heal numeric(8,2) := 0;
  v_actual_heal numeric(8,2) := 0;
  v_new_health numeric(5,1);
  v_active boolean := false;
  v_next_ms integer := 2000;
begin
  select * into v_effect
  from public.hospital_treatment_effects
  where patient_tg_id = trim(p_patient_tg_id) and status = 'active'
  order by started_at desc
  limit 1
  for update skip locked;

  select health into v_health from public.players where tg_id::text = trim(p_patient_tg_id) for update;
  if v_health is null then raise exception 'PLAYER_NOT_FOUND'; end if;
  if v_effect.id is null then
    return jsonb_build_object('active', false, 'health', v_health, 'healed', 0, 'nextPollMs', 0);
  end if;

  v_until := least(now(), v_effect.expires_at);
  v_ticks := greatest(0, floor(extract(epoch from (v_until - v_effect.last_processed_at)) / v_effect.tick_seconds)::integer);

  if v_ticks > 0 then
    v_heal := v_ticks * v_effect.heal_per_tick;
    v_new_health := least(100::numeric, v_health + v_heal);
    v_actual_heal := greatest(0::numeric, v_new_health - v_health);
    update public.players set health = v_new_health where tg_id::text = trim(p_patient_tg_id);
    v_health := v_new_health;
    update public.hospital_treatment_effects
    set last_processed_at = last_processed_at + make_interval(secs => v_ticks * tick_seconds)
    where id = v_effect.id;
    v_effect.last_processed_at := v_effect.last_processed_at + make_interval(secs => v_ticks * v_effect.tick_seconds);
    update public.hospital_employee_stats
    set health_restored = health_restored + v_actual_heal, updated_at = now()
    where hospital_id = v_effect.hospital_id and employee_tg_id = v_effect.clinician_tg_id;
  end if;

  if now() >= v_effect.expires_at or v_health >= 100 then
    update public.hospital_treatment_effects set status = 'completed' where id = v_effect.id;
    v_active := false;
    v_next_ms := 0;
  else
    v_active := true;
    v_next_ms := greatest(500, least(10000,
      ceil(v_effect.tick_seconds * 1000 - extract(epoch from (now() - v_effect.last_processed_at)) * 1000)::integer
    ));
  end if;

  return jsonb_build_object('active', v_active, 'health', v_health, 'healed', v_actual_heal, 'nextPollMs', v_next_ms);
end;
$$;


create or replace function public.hospital_set_employee_rank(
  p_hospital_id text, p_actor_tg_id text, p_target text, p_rank text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_access record;
  v_target_tg_id text;
  v_target_current_rank text;
  v_rank text := lower(trim(coalesce(p_rank, '')));
begin
  if v_rank not in ('junior', 'middle', 'senior', 'dismissed') then raise exception 'RANK_INVALID'; end if;
  select * into v_access from public.hospital_get_actor_access(p_hospital_id, p_actor_tg_id);
  if not coalesce(v_access.allowed, false) or (not v_access.is_admin and v_access.rank_level < 3) then
    raise exception 'EMPLOYEE_MANAGEMENT_DENIED';
  end if;

  v_target_tg_id := public.hospital_resolve_player_tg_id(p_target);
  if v_target_tg_id is null then raise exception 'PLAYER_NOT_FOUND'; end if;
  if v_target_tg_id = trim(p_actor_tg_id) and not v_access.is_admin then raise exception 'CANNOT_CHANGE_OWN_RANK'; end if;

  select rank into v_target_current_rank
  from public.hospital_employees
  where hospital_id = trim(p_hospital_id) and employee_tg_id = v_target_tg_id and active is true;
  if not v_access.is_admin and (v_rank = 'senior' or v_target_current_rank = 'senior') then
    raise exception 'ADMIN_REQUIRED_FOR_SENIOR_RANK';
  end if;

  if v_rank = 'dismissed' then
    update public.hospital_employees
    set active = false, appointed_by_tg_id = trim(p_actor_tg_id), updated_at = now()
    where hospital_id = trim(p_hospital_id) and employee_tg_id = v_target_tg_id;
  else
    insert into public.hospital_employees(hospital_id, employee_tg_id, rank, appointed_by_tg_id, active)
    values (trim(p_hospital_id), v_target_tg_id, v_rank, trim(p_actor_tg_id), true)
    on conflict (hospital_id, employee_tg_id) do update
      set rank = excluded.rank, active = true, appointed_by_tg_id = excluded.appointed_by_tg_id, updated_at = now();
    insert into public.hospital_employee_stats(hospital_id, employee_tg_id)
    values (trim(p_hospital_id), v_target_tg_id)
    on conflict (hospital_id, employee_tg_id) do nothing;
  end if;

  return jsonb_build_object('tgId', v_target_tg_id, 'rank', v_rank);
end;
$$;

